package org.rc.apiCollect.basicApi.lang.String;

public class BStringConstantPool {
    // 字符串常量池（String Constant Pool）是 Java 中用于存储字符串字面量和通过 intern() 方法获取的字符串的一个特殊区域。
    // 理解字符串常量池的位置及其工作原理对于优化内存使用和提高程序性能非常重要。
    //
    // 字符串常量池的位置
    //     在早期版本的 Java（Java 6 及之前），字符串常量池位于 永久代（Permanent Generation, PermGen），这是方法区的一部分。
    //     永久代用于存储类的元数据信息，如类的结构、静态变量等。
    //
    //     然而，从 Java 7 开始，为了更好地管理内存和优化垃圾回收，字符串常量池被移动到了 堆空间（Heap Space）。
    //     这一改变使得字符串常量池可以像其他对象一样被垃圾回收，并且堆空间通常比永久代大得多，从而减少了因字符串过多而导致的内存溢出风险。
    //
    // 总结位置变化：
    //     Java 6 及之前：字符串常量池位于永久代（PermGen），即方法区。
    //     Java 7 及之后：字符串常量池位于堆空间（Heap Space）。
    //
    // 字符串常量池的工作原理
    //     字符串字面量：当你在代码中直接使用双引号定义字符串（例如 String s = "hello";），这个字符串会被自动放入字符串常量池中。
    //         如果池中已经存在相同的字符串，则不会创建新的副本，而是返回已有的引用。
    //     new 关键字：使用 new 创建字符串时（例如 String s = new String("hello");），这种情况下，即使字符串常量池中已经有了相同的内容，
    //         也会在堆上创建一个新的 String 对象。这会导致两个不同的对象，一个在堆上，另一个在常量池中。
    //     intern() 方法：调用 String.intern() 方法会检查字符串常量池中是否存在该字符串。如果存在，则返回池中的引用；
    //         如果不存在，则将该字符串添加到池中并返回其引用。

    public static void main(String[] args) {
        // 字符串字面量，放入字符串常量池
        String str1 = "hello";
        String str2 = "hello";

        // 使用 new 关键字，在堆上创建新对象
        String str3 = new String("hello");

        // 调用 intern() 方法，确保在字符串常量池中有该字符串
        String str4 = str3.intern();

        System.out.println(str1 == str2); // true，引用相同
        System.out.println(str1 == str3); // false，不同对象
        System.out.println(str1 == str4); // true，str4 引用常量池中的 "hello"
    }

    // 在这个例子中：
    //     str1 和 str2 都是指向字符串常量池中的 "hello"，因此它们相等。
    //     str3 是通过 new 关键字创建的新对象，与常量池中的 "hello" 不同，所以 str1 == str3 返回 false。
    //     str4 调用了 str3.intern()，它指向了字符串常量池中的 "hello"，因此 str1 == str4 返回 true。
    //
    // 字符串常量池的好处
    //     节省内存：避免重复创建相同的字符串对象，减少内存占用。
    //     提高性能：由于字符串比较可以直接比较引用，而不需要逐字符比较，这提高了性能。
    //     便于共享：多个地方使用的相同字符串可以通过常量池共享同一个实例。
    //
    // 注意事项
    //     内存泄漏风险：不当使用 intern() 方法可能会导致内存泄漏，因为常量池中的字符串不会轻易被垃圾回收。
    //     性能影响：虽然常量池有助于节省内存和提高性能，但在高并发环境下频繁调用 intern() 可能会影响性能，因为它需要进行查找操作。
    //
    // 总结
    //     位置：从 Java 7 开始，字符串常量池位于堆空间，而在 Java 6 及之前位于方法区（永久代）。
    //     工作原理：它存储字符串字面量和通过 intern() 方法获取的字符串，以节省内存和提高性能。
    //     最佳实践：谨慎使用 intern() 方法，特别是在高并发环境中，以避免潜在的性能问题和内存泄漏。
    // 理解字符串常量池的位置和工作原理可以帮助你编写更高效的 Java 程序，合理利用内存资源，并避免常见的陷阱。



    // string s;
    // 在 Java 中，如果你声明了一个引用类型的变量（例如 String s;），但没有对其进行初始化，那么这个变量的值取决于它是在什么上下文中声明的。
    // 具体来说，Java 对类成员变量和局部变量有不同的默认初始化规则。
    //
    // 类成员变量（实例变量和静态变量）
    //     对于类中的成员变量（无论是实例变量还是静态变量），Java 会自动赋予它们默认值。对于 String 类型，默认值是 null。
    // 局部变量
    //     与成员变量不同，局部变量（即在方法、构造函数或块内部声明的变量）不会被自动初始化。如果你尝试在未初始化的情况下使用局部变量，
    //     编译器会抛出错误，提示你该变量可能还没有被初始化。
    //
    // 总结
    //     类成员变量：无论是实例变量还是静态变量，如果未显式初始化，Java 会自动将它们设置为 null。
    //     局部变量：必须显式初始化，否则编译器会报错，防止潜在的 NullPointerException。
}
