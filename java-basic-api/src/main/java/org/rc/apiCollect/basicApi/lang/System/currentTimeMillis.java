package org.rc.apiCollect.basicApi.lang.System;

public class currentTimeMillis {
    public static void main(String[] args) {
        // 返回当前时间与 1970 年1 月 1 日 0 时 0 分 0 秒之间以 毫秒 为单位的时间差。
        System.out.println(System.currentTimeMillis());



        // 计算世界时间的主要标准有：
        //     – UTC(Coordinated Universal Time)
        //     – GMT(Greenwich Mean Time)
        //     – CST(Central Standard Time)
        //
        // 在国际无线电通信场合，为了统一起见，使用一个统一的时间，称为通用协调时(UTC, Universal Time Coordinated)。
        // UTC 与格林尼治平均时(GMT, Greenwich Mean Time)一样，都与英国伦敦的本地时相同。这里，UTC 与 GMT 含义完全相同。
    }
}
