package org.rc.apiCollect.basicApi.util.Map.HashMap.ALearn;

public class ALearn {
    // • HashMap 是 Map 接口使用频率最高的实现类。
    // • HashMap 是线程不安全的。允许添加 null 键和 null 值。
    // • 存储数据采用的哈希表结构，底层使用 一维数组 + 单向链表 + 红黑树进行 key-value 数据的存储。
    //      与 HashSet 一样，元素的存取顺序不能保证一致。
    // • HashMap 判断两个 key 相等的标准是：两个 key 的 hashCode 值相等，通过 equals() 方法返回 true。
    // • HashMap 判断两个 value 相等的标准是：两个 value 通过 equals() 方法返回true。



}
